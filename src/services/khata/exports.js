import Native from '../../../modules/reminder-native';
import { formatPaise, TYPE_LABEL } from './money';
import { whatsappNumber } from './share';
import { fmtDateStr, fmtDateLong, MONTHS, parseDateStr } from '../../utils/date';

const pad = (n) => String(n).padStart(2, '0');
const stampText = (now) => `${now.getDate()} ${MONTHS[now.getMonth()]} ${now.getFullYear()}`;
const stampLong = (now) => {
  const h = now.getHours();
  return `${stampText(now)}, ${((h + 11) % 12) + 1}:${pad(now.getMinutes())} ${h >= 12 ? 'PM' : 'AM'}`;
};
const slug = (s) => String(s || 'khata').normalize('NFKD').replace(/[^\w]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 30) || 'khata';
const day = (s) => { const d = parseDateStr(s); return `${d.getDate()} ${MONTHS[d.getMonth()]}`; };
const file = (prefix, name, now) => `${prefix}_${slug(name)}_${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}_${pad(now.getHours())}${pad(now.getMinutes())}`;

const direction = (out) => (out > 0 ? { label: 'THEY OWE ME', tone: 'green' } : out < 0 ? { label: 'I OWE THEM', tone: 'red' } : { label: 'ALL SETTLED', tone: 'grey' });
const balText = (net) => `Bal ${formatPaise(Math.abs(net))}${net > 0 ? ' Lena' : net < 0 ? ' Dena' : ''}`;
const entryTone = (type) => (type === 'lena' || type === 'received' ? 'green' : 'red');

/** Full ledger for one person (newest first) with the running balance after each active entry. */
export function personStatementModel({ contact, totals, entries, now = new Date() }) {
  const asc = [...entries].sort((a, b) => (a.date === b.date ? a.id - b.id : a.date < b.date ? -1 : 1));
  const SIGN = { lena: 1, given: 1, dena: -1, received: -1 };
  let run = 0;
  const balAfter = new Map();
  for (const e of asc) { if (e.status === 'active') { run += SIGN[e.type] * e.amount_paise; balAfter.set(e.id, run); } }
  const d = direction(totals.outstanding);
  return {
    fileName: file('khata', contact.name, now), title: 'Khata statement', date: stampText(now),
    name: contact.name, subtitle: contact.phone || '',
    headline: { label: d.label, amount: formatPaise(Math.abs(totals.outstanding)), tone: d.tone },
    stats: [
      { label: 'LENA', value: formatPaise(totals.lena) }, { label: 'DENA', value: formatPaise(totals.dena) },
      { label: 'RECEIVED', value: formatPaise(totals.received) }, { label: 'GIVEN', value: formatPaise(totals.given) },
    ],
    section: 'TRANSACTIONS',
    rows: [...asc].reverse().map((e) => ({
      date: day(e.date), title: TYPE_LABEL[e.type], note: e.note || '', amount: formatPaise(e.amount_paise),
      tone: entryTone(e.type), deleted: e.status === 'deleted', balance: e.status === 'active' ? balText(balAfter.get(e.id)) : 'deleted',
    })),
    footer: `Generated by GAURAV OS · ${stampLong(now)}`,
  };
}

/** Everyone with a balance (largest first) plus totals. */
export function allKhataModel({ summary, people, now = new Date() }) {
  const d = summary.net > 0 ? 'green' : summary.net < 0 ? 'red' : 'grey';
  return {
    fileName: file('khata_all', 'summary', now), title: 'My Khata summary', date: stampText(now), name: '', subtitle: '',
    headline: { label: summary.net > 0 ? 'NET: PEOPLE OWE ME' : summary.net < 0 ? 'NET: I OWE PEOPLE' : 'NET BALANCE', amount: formatPaise(Math.abs(summary.net)), tone: d },
    stats: [
      { label: 'MUJHE LENA HAI', value: formatPaise(summary.receivable) }, { label: 'MUJHE DENA HAI', value: formatPaise(summary.payable) },
      { label: 'OUTSTANDING', value: String(summary.outstanding) }, { label: 'PEOPLE', value: String(summary.people) },
    ],
    section: 'PEOPLE',
    rows: people.map((p) => ({
      date: p.last_date ? day(p.last_date) : '', title: p.name, note: p.phone || '',
      amount: p.net_paise === 0 ? 'Settled' : formatPaise(Math.abs(p.net_paise)),
      tone: p.net_paise > 0 ? 'green' : p.net_paise < 0 ? 'red' : 'grey', balance: p.net_paise > 0 ? 'Lena' : p.net_paise < 0 ? 'Dena' : '',
    })),
    footer: `Generated by GAURAV OS · ${stampLong(now)}`,
  };
}

/** One-transaction receipt. `outstanding` is the person's current balance (paise). */
export function receiptModel({ contact, entry, outstanding, now = new Date() }) {
  const rows = [
    { title: 'Date', amount: fmtDateStr(entry.date) + ` ${parseDateStr(entry.date).getFullYear()}` },
    { title: 'Type', amount: TYPE_LABEL[entry.type] },
    ...(entry.note ? [{ title: 'Note', amount: entry.note }] : []),
    ...(entry.status === 'deleted' ? [{ title: 'Status', amount: 'Deleted', tone: 'red' }] : []),
    { title: 'Recorded on', amount: stampText(new Date(entry.created_at)) },
    { title: 'Balance with this person', amount: outstanding === 0 ? 'Settled' : `${formatPaise(Math.abs(outstanding))} ${outstanding > 0 ? '(they owe me)' : '(I owe them)'}` },
  ];
  return {
    fileName: file('receipt', `${contact.name}_${entry.id}`, now), title: 'Transaction receipt', date: stampText(now),
    name: contact.name, subtitle: contact.phone || '',
    headline: { label: TYPE_LABEL[entry.type].toUpperCase(), amount: formatPaise(entry.amount_paise), tone: entryTone(entry.type) },
    stats: [], section: 'DETAILS', rows, footer: `Generated by GAURAV OS · ${stampLong(now)}`,
  };
}

const realDeps = () => ({ native: Native, sharing: require('expo-sharing') });

/** Render a model to PDF and open the share sheet (Drive, WhatsApp, Files...). Returns the file path. */
export async function exportPdf(model, deps = realDeps()) {
  if (!deps.native?.renderStatement) throw new Error('PDF export needs the installed Android app.');
  const path = await deps.native.renderStatement(JSON.stringify(model), 'pdf', 100000);
  if (!(await deps.sharing.isAvailableAsync())) throw new Error(`Sharing is not available. The PDF was saved at ${path}`);
  await deps.sharing.shareAsync(`file://${path}`, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf', dialogTitle: model.title });
  return path;
}

/**
 * Render the balance image and open WhatsApp/SMS with it + the message attached. Never sends: the user presses Send.
 * Returns {ok, reason}. Callers fall back to the text-only link when ok is false.
 */
export async function sendReminderWithImage(channel, contact, message, model, { countryCode = '91' } = {}, deps = realDeps()) {
  if (!deps.native?.shareImageTo) return { ok: false, reason: 'Sending an image needs the installed Android app.' };
  if (!message) return { ok: false, reason: 'Nothing is pending with this person.' };
  const digits = channel === 'whatsapp' ? whatsappNumber(contact.phone, countryCode) : String(contact.phone || '').replace(/[^\d+]/g, '');
  if (!digits) return { ok: false, reason: 'This person has no phone number saved.' };
  try {
    const path = await deps.native.renderStatement(JSON.stringify(model), 'png', 8);
    const status = await deps.native.shareImageTo(path, channel, digits, message);
    return status === 'ok' ? { ok: true, path } : { ok: false, reason: status };
  } catch (e) { return { ok: false, reason: e.message }; }
}
